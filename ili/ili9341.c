void LCD_FillArea(uint16_t x, uint16_t y,
                  uint16_t w, uint16_t h, uint16_t color)
{
    uint32_t cnt;
    uint8_t hi, lo;
    uint16_t xend, yend;

    if (w == 0 || h == 0) return;
    if (x >= LCD_WIDTH || y >= LCD_HEIGHT) return;

    xend = (uint16_t)(x + w - 1);
    yend = (uint16_t)(y + h - 1);
    if (xend >= LCD_WIDTH)  xend = LCD_WIDTH  - 1;    
    if (yend >= LCD_HEIGHT) yend = LCD_HEIGHT - 1;    

    hi = (uint8_t)(color >> 8);
    lo = (uint8_t)(color & 0xFF);

    set_window(x, y, xend, yend);
    ram_start();
    for (cnt = (uint32_t)(xend - x + 1) * (uint32_t)(yend - y + 1);
         cnt != 0; cnt--) {
        spi_write_const(hi);
        spi_write_const(lo);
    }
    ram_end();
}

 
void LCD_ShowImage256(uint16_t x, uint16_t y,
                      uint16_t w, uint16_t h,
                      const uint16_t *palette, const uint8_t *img)
{
    uint32_t i, total;
    uint16_t color;

    if (img == 0 || palette == 0 || w == 0 || h == 0) return;
    if (x >= LCD_WIDTH || y >= LCD_HEIGHT) return;

    if ((uint32_t)x + w > LCD_WIDTH)  w = (uint16_t)(LCD_WIDTH  - x);   
    if ((uint32_t)y + h > LCD_HEIGHT) h = (uint16_t)(LCD_HEIGHT - y);   

    set_window(x, y, (uint16_t)(x + w - 1), (uint16_t)(y + h - 1));
    ram_start();
    total = (uint32_t)w * h;
    for (i = 0; i < total; i++) {
        color = palette[img[i]];                     
        spi_write_byte((uint8_t)(color >> 8));       
        spi_write_byte((uint8_t)(color & 0xFF));     
    }
    ram_end();
}

 
