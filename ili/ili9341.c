void LCD_ShowStringCentered(const char *s, uint16_t fc, uint16_t bc, uint8_t size)
{
    const char *p = s;
    uint16_t n = 0;
    uint16_t x, y, w, h;
    uint8_t sz = size ? size : 1;

    while (*p) { n++; p++; }
    if (n == 0) return;

    w = (uint16_t)(n * (8 * sz + 2 * sz) - 2 * sz);
    h = (uint16_t)(16 * sz);
    x = (w < LCD_WIDTH) ? (uint16_t)((LCD_WIDTH - w) / 2) : 0;
    y = (uint16_t)((LCD_HEIGHT - h) / 2);

    LCD_ShowString(x, y, s, fc, bc, sz);
}

 

 
uint16_t LCD_RGB(uint8_t r, uint8_t g, uint8_t b)
{
    uint16_t rr = (uint16_t)(r >> 3);    
    uint16_t gg = (uint16_t)(g >> 2);    
    uint16_t bb = (uint16_t)(b >> 3);    
    return (uint16_t)((rr << 11) | (gg << 5) | bb);
}

 
