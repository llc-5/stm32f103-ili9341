static void delay_ms(uint32_t ms)
{
    volatile uint32_t i;

    while (ms--) {
        for (i = 0; i < 8000U; i++) {
             
        }
    }
}

 
static void spi_write_byte(uint8_t dat)
{
    uint8_t i;

    for (i = 0; i < 8; i++) {
        LCD_SCK_L();
        if (dat & 0x80) { LCD_SDI_H(); } else { LCD_SDI_L(); }
        dat <<= 1;
        LCD_SCK_H();                         
    }
    LCD_SCK_L();
}

 
static void spi_write_const(uint8_t dat)
{
    uint8_t i;

    if (dat == 0xFF) {
        LCD_SDI_H();
    } else if (dat == 0x00) {
        LCD_SDI_L();
    } else {
        spi_write_byte(dat);
        return;
    }
    for (i = 0; i < 8; i++) {
        LCD_SCK_L();
        LCD_SCK_H();
    }
    LCD_SCK_L();
}

static void write_cmd(uint8_t cmd)
{
    LCD_CS_L();
    LCD_DC_L();
    spi_write_byte(cmd);
    LCD_CS_H();
}

 
static void write_cmd_data(uint8_t cmd, const uint8_t *dat, uint8_t n)
{
    LCD_CS_L();
    LCD_DC_L();
    spi_write_byte(cmd);
    LCD_DC_H();
    while (n--) {
        spi_write_byte(*dat++);
    }
    LCD_CS_H();
}

static void ram_start(void)
{
    LCD_CS_L();
    LCD_DC_L();
    spi_write_byte(0x2C);
    LCD_DC_H();
}

static void ram_end(void)
{
    LCD_CS_H();
}

static void set_window(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1)
{
    uint8_t p[4];

    p[0] = (uint8_t)(x0 >> 8);
    p[1] = (uint8_t)(x0 & 0xFF);
    p[2] = (uint8_t)(x1 >> 8);
    p[3] = (uint8_t)(x1 & 0xFF);
    write_cmd_data(0x2A, p, 4);

    p[0] = (uint8_t)(y0 >> 8);
    p[1] = (uint8_t)(y0 & 0xFF);
    p[2] = (uint8_t)(y1 >> 8);
    p[3] = (uint8_t)(y1 & 0xFF);
    write_cmd_data(0x2B, p, 4);
}

 
static void gpio_init(void)
{
    uint32_t crl;

    LCD_RCC_APB2ENR |= (1UL << 2);           
    LCD_RCC_APB2ENR &= ~(1UL << 12);          

    crl  = LCD_GPIOA->CRL;
    crl &= ~((0xFUL << 0) | (0xFUL << 4) | (0xFUL << 8) |
             (0xFUL << 20) | (0xFUL << 28));
    crl |=  ((0x3UL << 0) | (0x3UL << 4) | (0x3UL << 8) |
             (0x3UL << 20) | (0x3UL << 28));
#if LCD_LED_CTRL
    crl &= ~(0xFUL << (4UL * LCD_LED_PIN));
    crl |=  (0x3UL << (4UL * LCD_LED_PIN));
#endif
    LCD_GPIOA->CRL = crl;

#if LCD_LED_CTRL
    LCD_LED_H();                             
#endif
    LCD_CS_H();                              
    LCD_RES_H();                              
    LCD_SCK_L();                              
    LCD_DC_H();
    LCD_SDI_L();
}

 
void LCD_Init(void)
{
    uint8_t p[4];

    gpio_init();

    LCD_RES_H();
    delay_ms(20);
    LCD_RES_L();
    delay_ms(20);
    LCD_RES_H();
    delay_ms(120);

    write_cmd(0x01);                         
    delay_ms(100);
    write_cmd(0x11);                         
    delay_ms(120);

     
    p[0] = 0x55;
    write_cmd_data(0x3A, p, 1);              
    p[0] = (uint8_t)LCD_MADCTL_VALUE;
    write_cmd_data(0x36, p, 1);              
    p[0] = 0x01;
    write_cmd_data(0x26, p, 1);              

#if LCD_USE_EXTENDED_INIT
    write_cmd_data(0xB1, INIT_B1, 2);        
    write_cmd_data(0xB6, INIT_B6, 3);        
    write_cmd_data(0xC0, INIT_C0, 1);        
    write_cmd_data(0xC1, INIT_C1, 1);        
    write_cmd_data(0xC5, INIT_C5, 2);        
    write_cmd_data(0xC7, INIT_C7, 1);        
    write_cmd_data(0xE0, INIT_E0, 15);
    write_cmd_data(0xE1, INIT_E1, 15);
#endif

    write_cmd(0x20);                         
    write_cmd(0x13);                         
    write_cmd(0x29);                         
    delay_ms(30);

    LCD_ClearScreen();                       
}

 
void LCD_Fill(uint16_t color)
{
    uint32_t i, total;
    uint8_t hi = (uint8_t)(color >> 8);
    uint8_t lo = (uint8_t)(color & 0xFF);

    total = (uint32_t)LCD_WIDTH * (uint32_t)LCD_HEIGHT;
    set_window(0, 0, LCD_WIDTH - 1, LCD_HEIGHT - 1);
    ram_start();
    for (i = 0; i < total; i++) {
        spi_write_const(hi);
        spi_write_const(lo);
    }
    ram_end();
}

 
static const uint8_t *get_glyph(char ch)
{
    if (ch >= '0' && ch <= '9') return FONT_8x16[ch - '0'];
    if (ch >= 'A' && ch <= 'Z') return FONT_UPPER[ch - 'A'];
    if (ch >= 'a' && ch <= 'z') return FONT_LOWER[ch - 'a'];
    return FONT_BLANK;
}

 
static uint8_t g_lcd_bg_transparent = 1;

void LCD_SetBgTransparent(uint8_t enable)
{
    g_lcd_bg_transparent = enable ? 1u : 0u;
}

 
static void draw_char_transparent(uint16_t x, uint16_t y, const uint8_t *g,
                                  uint16_t fc, uint8_t size)
{
    uint8_t row, col, rep_y, b;
    uint8_t fhi, flo;
    uint16_t cw, chh, run, i;

    if (size == 0) size = 1;
    cw  = (uint16_t)(8 * size);
    chh = (uint16_t)(16 * size);
    if (x + cw > LCD_WIDTH || y + chh > LCD_HEIGHT) return;

    fhi = (uint8_t)(fc >> 8);
    flo = (uint8_t)(fc & 0xFF);

    for (row = 0; row < 16; row++) {
        b = g[row];
        for (rep_y = 0; rep_y < size; rep_y++) {
            uint16_t yy = (uint16_t)(y + row * size + rep_y);
            run = 0;                             
            for (col = 0; col <= 8; col++) {
                if (col < 8 && (b & (uint8_t)(0x80 >> col))) {
                    run++;                       
                } else if (run > 0) {            
                    uint16_t x0 = (uint16_t)(x + (col - run) * size);
                    uint16_t x1 = (uint16_t)(x + col * size - 1);
                    set_window(x0, yy, x1, yy);
                    ram_start();
                    for (i = x0; i <= x1; i++) {
                        spi_write_const(fhi);
                        spi_write_const(flo);
                    }
                    ram_end();
                    run = 0;
                }
            }
        }
    }
}

 
static void draw_char(uint16_t x, uint16_t y, const uint8_t *g,
                      uint16_t fc, uint16_t bc, uint8_t size)
{
    uint8_t row, col, rep_y, rep_x, b;
    uint8_t fhi, flo, bhi, blo;
    uint16_t cw, chh;

    if (size == 0) size = 1;
    cw  = (uint16_t)(8 * size);
    chh = (uint16_t)(16 * size);
    if (x + cw > LCD_WIDTH || y + chh > LCD_HEIGHT) return;

    if (g_lcd_bg_transparent) {                  
        draw_char_transparent(x, y, g, fc, size);
        return;
    }

    fhi = (uint8_t)(fc >> 8);
    flo = (uint8_t)(fc & 0xFF);
    bhi = (uint8_t)(bc >> 8);
    blo = (uint8_t)(bc & 0xFF);

    set_window(x, y, x + cw - 1, y + chh - 1);
    ram_start();
    for (row = 0; row < 16; row++) {
        b = g[row];
        for (rep_y = 0; rep_y < size; rep_y++) {
            for (col = 0; col < 8; col++) {
                for (rep_x = 0; rep_x < size; rep_x++) {
                    if (b & (uint8_t)(0x80 >> col)) {
                        spi_write_const(fhi);
                        spi_write_const(flo);
                    } else {
                        spi_write_const(bhi);
                        spi_write_const(blo);
                    }
                }
            }
        }
    }
    ram_end();
}

 
void LCD_ShowChar(uint16_t x, uint16_t y, char ch,
                  uint16_t fc, uint16_t bc, uint8_t size)
{
    draw_char(x, y, get_glyph(ch), fc, bc, size);
}

 
